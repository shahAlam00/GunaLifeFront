import React, { useEffect, useRef, useState } from "react";

/* ───────────── Scroll-in-view hook ───────────── */
export function useInView(threshold = 0.2) {
  const ref = useRef(null);
  const [inView, setInView] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const io = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          setInView(true);
          io.disconnect();
        }
      },
      { threshold }
    );
    io.observe(el);
    return () => io.disconnect();
  }, [threshold]);

  return [ref, inView];
}

/* ───────────── Fade-up reveal wrapper ───────────── */
export function Reveal({ children, delay = 0, className = "" }) {
  const [ref, inView] = useInView(0.15);
  return (
    <div
      ref={ref}
      style={{ transitionDelay: `${delay}ms` }}
      className={`transition-all duration-700 ease-out ${
        inView ? "translate-y-0 opacity-100" : "translate-y-6 opacity-0"
      } ${className}`}
    >
      {children}
    </div>
  );
}

/* ───────────── Animated number ───────────── */
export function CountUp({ to, suffix = "", duration = 1600 }) {
  const [ref, inView] = useInView(0.4);
  const [val, setVal] = useState(0);

  useEffect(() => {
    if (!inView) return;
    let raf;
    const start = performance.now();
    const tick = (now) => {
      const p = Math.min((now - start) / duration, 1);
      const eased = 1 - Math.pow(1 - p, 3);
      setVal(Math.round(to * eased));
      if (p < 1) raf = requestAnimationFrame(tick);
    };
    raf = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(raf);
  }, [inView, to, duration]);

  return (
    <span ref={ref}>
      {val}
      {suffix}
    </span>
  );
}

/* ───────────── Image with branded fallback ─────────────
   Put your real photos in /public/images/quality/...
   If the file is missing, a blurred GunaLife gradient shows instead. */
export function SmartImage({ src, alt = "GunaLife", className = "" }) {
  const [failed, setFailed] = useState(!src);

  if (failed) {
    return (
      <div
        role="img"
        aria-label={alt}
        className={`relative overflow-hidden ${className}`}
        style={{
          background:
            "linear-gradient(135deg, var(--brand-deep), var(--brand-light) 55%, var(--brand-teal))",
        }}
      >
        <span className="absolute inset-0 flex select-none items-center justify-center text-5xl font-extrabold tracking-tight text-white opacity-30 blur-md sm:text-7xl">
          GunaLife
        </span>
      </div>
    );
  }

  return (
    <img
      src={src}
      alt={alt}
      loading="lazy"
      onError={() => setFailed(true)}
      className={`object-cover ${className}`}
    />
  );
}

/* ───────────── Section heading ───────────── */
export function SectionHeading({ eyebrow, title, text, light = false, center = true }) {
  return (
    <div className={`max-w-2xl ${center ? "mx-auto text-center" : ""}`}>
      <span
        className={`inline-block text-xs font-bold uppercase tracking-[0.25em] ${
          light ? "text-blush" : "text-[color:var(--brand-teal)]"
        }`}
      >
        {eyebrow}
      </span>
      <h2
        className={`mt-3 text-3xl font-extrabold leading-tight tracking-tight sm:text-4xl lg:text-[44px] ${
          light ? "text-white" : "text-brand-primary"
        }`}
      >
        {title}
      </h2>
      {text && (
        <p
          className={`mt-4 leading-relaxed ${
            light ? "text-white/75" : "text-[color:var(--text-muted)]"
          }`}
        >
          {text}
        </p>
      )}
    </div>
  );
}

